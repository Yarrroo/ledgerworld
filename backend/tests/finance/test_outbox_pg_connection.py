class InTransactionConnection:
    """Match psycopg's refusal to change isolation while a transaction is open."""

    @property
    def isolation_level(self):
        return "READ COMMITTED"

    @isolation_level.setter
    def isolation_level(self, _value):
        raise ProgrammingError("can't change 'isolation_level' now: connection in transaction")


@contextmanager
def transaction():
    yield


@pytest.mark.parametrize("managed", [False, True])
def test_outbox_does_not_change_a_server_connections_isolation(managed):
    conn = InTransactionConnection()
    box = ob.Outbox(conn, lambda _conn, _leg: "journal",
                    transaction=transaction if managed else None)
    assert box.conn is conn


class LegacyEventsConnection(RecordingConnection):
    """An existing server table without SQLite's implicit event numbering."""

    next_seq = 42

    def execute(self, sql, params=()):
        super().execute(sql, params)
        if "information_schema.columns" in sql:
            self._row = (None, "NO")
        elif "MAX(event_seq)" in sql:
            self._row = (self.next_seq,)
        return self


def test_install_numbers_server_events_and_preserves_existing_ids():
    fresh = LegacyEventsConnection(tables=set())
    fresh.next_seq = 1
    ob.install(fresh)
    assert any("ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1)" in s
               for s in fresh.statements)
    legacy = LegacyEventsConnection(tables={"execution_legs"})
    ob.install(legacy)
    lock = legacy.statements.index("LOCK TABLE leg_events IN ACCESS EXCLUSIVE MODE")
    probes = [i for i, s in enumerate(legacy.statements) if "information_schema.columns" in s]
    assert probes[0] < lock < probes[1]
    assert any("ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 42)" in s
               for s in legacy.statements)
    assert legacy.commits == 1


def test_install_does_not_reset_an_existing_server_identity():
    class IdentityConnection(RecordingConnection):
        def execute(self, sql, params=()):
            super().execute(sql, params)
            if "information_schema.columns" in sql:
                self._row = (None, "YES")
            return self

    conn = IdentityConnection(tables={"execution_legs"})
    ob.install(conn)
    assert not any("ALTER TABLE" in s or "MAX(event_seq)" in s for s in conn.statements)
    assert not any("LOCK TABLE" in s for s in conn.statements)
    assert conn.commits == 1


def test_failed_server_identity_install_rolls_back():
    class FailingConnection(LegacyEventsConnection):
        def execute(self, sql, params=()):
            super().execute(sql, params)
            if "ALTER TABLE" in sql:
                raise ProgrammingError("identity install failed")
            return self

    conn = FailingConnection(tables={"execution_legs"})
    with pytest.raises(ProgrammingError, match="identity install failed"):
        ob.install(conn)
    assert conn.rolled_back == 1
    assert conn.commits == 0


def test_managed_sqlite_outbox_does_not_commit_the_callers_transaction():
    conn = sqlite3.connect(":memory:")
    try:
        conn.execute("PRAGMA foreign_keys = ON")
        conn.execute("CREATE TABLE marker (value INTEGER)")
        conn.execute("INSERT INTO marker VALUES (1)")
        ob.Outbox(conn, lambda _conn, _leg: "journal", transaction=transaction)
        assert conn.in_transaction
        conn.rollback()
        assert conn.execute("SELECT * FROM marker").fetchall() == []
    finally:
        conn.close()


def test_managed_sqlite_refuses_disabled_foreign_keys_in_an_open_transaction():
    conn = sqlite3.connect(":memory:")
    try:
        conn.execute("CREATE TABLE marker (value INTEGER)")
        conn.execute("INSERT INTO marker VALUES (1)")
        with pytest.raises(ValueError, match="foreign keys"):
            ob.Outbox(conn, lambda _conn, _leg: "journal", transaction=transaction)
        assert conn.in_transaction
        conn.rollback()
        assert conn.execute("SELECT * FROM marker").fetchall() == []
    finally:
        conn.close()


class LegacySQLite(sqlite3.Connection):
    """SQLite before 3.39 refuses the long-form null-safe comparison."""

    def execute(self, sql, parameters=()):
        if "IS NOT DISTINCT FROM" in sql:
            raise sqlite3.OperationalError('near "DISTINCT": syntax error')
        return super().execute(sql, parameters)


def _seed_box(*, factory=sqlite3.Connection, provider_id=None):
    conn = sqlite3.connect(":memory:", factory=factory)
    ob.install(conn)
    box = ob.Outbox(conn, lambda _conn, _leg: "journal",
                    clock=lambda: "2026-01-01T00:00:00+00:00")
    conn.execute("INSERT INTO approvals VALUES ('a', 'e', 's', 'snapshot', 'hash', 'fake',"
                 " 'operator', '2026-01-01', '2026-01-02', NULL)")
    conn.execute(
        "INSERT INTO execution_legs (leg_id, approval_id, leg_index, kind, request_id,"
        " source_account, counterparty, currency, amount_minor, state, receipt_label,"
        " updated_at, provider_id) VALUES ('l', 'a', 1, 'payout', 'r', 's', 'c', 'USD',"
        " 1, 'pending', 'fake', '2026-01-01', ?)", (provider_id,))
    return box


@pytest.mark.parametrize("provider_id", [None, "provider-1"])
def test_leg_transitions_do_not_require_sqlite_339(provider_id):
    box = _seed_box(factory=LegacySQLite, provider_id=provider_id)
    try:
        leg = box.leg("l")
        assert box._move(leg, "submitted", "claimed")
        assert box.leg("l").state == "submitted"
        assert not box._move(leg, "submitted", "claimed")  # the stale claim loses
    finally:
        box.conn.close()


def test_leg_reads_accept_a_mapping_row_factory():
    box = _seed_box()
    try:
        box.conn.row_factory = lambda cursor, row: dict(zip(
            (d[0] for d in cursor.description), row, strict=True))
        leg = box.leg("l")
        assert (leg.leg_id, leg.amount_minor, leg.after) == ("l", 1, ())
    finally:
        box.conn.close()


def test_server_identity_is_rechecked_after_the_migration_lock():
    class RacedConnection(LegacyEventsConnection):
        probes = 0

        def execute(self, sql, params=()):
            super().execute(sql, params)
            if "information_schema.columns" in sql:
                self.probes += 1
                self._row = (None, "NO" if self.probes == 1 else "YES")
            return self

    conn = RacedConnection(tables={"execution_legs"})
    ob.install(conn)
    assert conn.probes == 2
    assert not any("ALTER TABLE" in s or "MAX(event_seq)" in s for s in conn.statements)


def _gateway(tmp_path):
    root = Path(__file__).resolve().parents[3]
    snapshot = json.loads((root / "fixtures/lf1_treasury.json").read_text())["snapshot"]
    now = datetime.fromisoformat(snapshot["as_of"])
    url = f"sqlite:///{tmp_path / 'ledger.sqlite'}"
    store = LedgerStore(url)
    from_snapshot(store, snapshot)
    store.engine.dispose()
    # Unlike StaticPool, separate checkouts need not share a driver connection.
    store.engine = create_engine(url, poolclass=QueuePool, pool_size=3)
    event.listen(store.engine, "connect", _sqlite_connect)
    event.listen(store.engine, "begin", _sqlite_begin)
    compiled = []

    def check_server_sql(_conn, _cursor, _sql, _params, context, _many):
        if context.compiled and isinstance(context.compiled.statement, TextClause):
            sql = str(context.compiled.statement.compile(dialect=postgresql.dialect()))
            assert "?" not in sql
            assert "BEGIN IMMEDIATE" not in sql
            compiled.append(sql)

    event.listen(store.engine, "before_cursor_execute", check_server_sql)
    clock = FakeClock()
    fake = FakeTransport(clock=clock, connected=False)
    client = AirwallexClient(fake, clock, api_version=DEFAULT_API_VERSION, sleep=lambda _: None)
    gateway = Gateway(store, client, mode="fake", leg_mode="B",
                      beneficiaries={"ben-payroll-1"}, clock=lambda: now)
    approval = bind({"entity": "borrower-a", "account": "borrower-a/operating", "legs": [{
        "index": 1, "kind": "payout", "source": "borrower-a/operating",
        "counterparty": "ben-payroll-1", "amount": {"minor": 5_000_000, "currency": "USD"},
        "funded_by": "reservation:res-payroll-1"}]},
        snapshot["snapshot_id"], "operator", "fake", now=now)
    return gateway, approval, client, compiled


@pytest.mark.parametrize("posting_fault", [False, True])
def test_gateway_uses_the_checked_out_transaction_for_outbox_and_ledger(tmp_path, posting_fault):
    gateway, approval, client, compiled = _gateway(tmp_path)
    store = gateway.store
    try:
        # Occupy the startup connection: retaining it after pool return used to split writes
        # from the ledger transaction (and is unsafe on a PostgreSQL QueuePool).
        with store.engine.connect():
            gateway.record(approval)
            result = gateway.execute(approval, current_snapshot_id=approval.snapshot_id)
            assert isinstance(result, Execution)
            leg = result.legs[0]
            assert leg.state == "submitted"
            for status in ("PROCESSING", "SENT", "PAID"):
                client.simulate_transition(leg.provider_id, status)
            before = store.rows("journals")
            write = gateway.outbox._write

            def fail_after_journal(*args, **kwargs):
                if args[1] == "settled":
                    raise RuntimeError("crash between journal and leg write")
                return write(*args, **kwargs)

            if posting_fault:
                gateway.outbox._write = fail_after_journal
                with pytest.raises(RuntimeError, match="crash between journal"):
                    gateway.run(approval.approval_id)
                assert store.rows("journals") == before
                assert gateway.legs(approval.approval_id)[0].state == "submitted"
                assert store.reservation("res-payroll-1").state == "committed"
                gateway.outbox._write = write
            settled = gateway.run(approval.approval_id)[0]
            assert settled.state == "settled" and settled.reconciled
            assert len(store.rows("journals")) == len(before) + 1
            assert store.reservation("res-payroll-1").state == "settled"
            assert gateway.stored(approval.approval_id) == approval
            assert gateway.conn.execute("SELECT ? || ':out'", (leg.leg_id,)).fetchone() == (
                f"{leg.leg_id}:out",)
            assert any("provider_id IS NULL" in sql for sql in compiled)
            assert any("provider_id = %(p" in sql for sql in compiled)
            assert store.engine.pool.checkedout() == 1
        assert store.engine.pool.checkedout() == 0
    finally:
        store.engine.dispose()
